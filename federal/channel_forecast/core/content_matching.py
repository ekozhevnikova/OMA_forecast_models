        result = re.sub(r'\s+', ' ', result).strip()

        if result == '':
            print(Color.BOLD + Color.RED + f'‼️ Строка {text} оказалась пустой для канала {self.channel}. Проверьте обработку текста!' + Color.END)
            return ''

        if debug:
            print(f"\n{'='*80}")
            print(f'ПОСЛЕ ФИНАЛЬНОЙ ОЧИСТКИ:           {result}')
