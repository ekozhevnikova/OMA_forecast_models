        for category, programs in self.programs.items():
            all_programs.extend([(program, category) for program in programs])
        
        # ЭТАП 4: Обрабатываем программы с использованием кэша
        unified_mapping = {}
        unique_programs = []
        seen = set()
        
        for program, category in all_programs:
            # Проверяем кэш
            cache_key = (program, category)
            if cache_key in self._clean_cache:
                cleaned = self._clean_cache[cache_key]
            else:
                cleaned = self.process_program_by_type(program, category, cities_dict)
                self._clean_cache[cache_key] = cleaned
            
            if cleaned is None:
                print(f"  ⚠️ ПРОБЛЕМА: программа '{program}' вернула None в категории '{category}'")
                continue
                
            unified_mapping[program] = cleaned
            
            # Используем set для быстрой проверки уникальности
            if cleaned not in seen:
                seen.add(cleaned)
                unique_programs.append(cleaned)
        
        # ЭТАП 5: Применяем маппинг
        result_df = df.copy()
        result_df['program_name'] = result_df[program_name_column].map(unified_mapping)
        
        return unique_programs, result_df


